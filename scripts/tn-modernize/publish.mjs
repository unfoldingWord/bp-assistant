#!/usr/bin/env node
// publish.mjs — deliver a modernize run as ONE open en_tn PR, one commit per book.
//
//   DOOR43_TOKEN=... node scripts/tn-modernize/publish.mjs [--branch tn-modernize-YYYY-MM-DD] \
//     [--org unfoldingWord] [--report-url <url>] [--dry] BOOK [BOOK...]
//
// Syncs a shallow en_tn clone to a fresh branch off master, splices each
// book's 'changed' results into that fresh copy (rows.applyResults: a row whose
// Note changed upstream since extract is left alone and listed), proves the
// file differs only in those Note cells, commits it, pushes, then opens the PR
// with createPR. It never merges: createPR has no merge step.
//
// --dry stops after the splice and the proof: nothing is committed or pushed.

import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';

const require = createRequire(import.meta.url);
const lib = require('./lib.js');
const { applyResults, diffOnlyNotes } = require('./rows.js');
const { syncRepo, commitAndPush, createPR, getConfig, checkConflictingBranches } = require('../../src/door43-push.js');

const argv = process.argv.slice(2);
const valueFlags = ['--branch', '--org', '--report-url'];
const flag = (n, d) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : d; };
const skipIdx = new Set(valueFlags.flatMap((f) => { const i = argv.indexOf(f); return i >= 0 ? [i, i + 1] : []; }));
const books = argv.filter((a, i) => !skipIdx.has(i) && /^[0-9A-Z]{3}$/.test(a));
const DRY = argv.includes('--dry');
const ORG = flag('--org', 'unfoldingWord');
const BRANCH = flag('--branch', `tn-modernize-${new Date().toISOString().slice(0, 10)}`);
const REPORT = flag('--report-url', '');
if (!books.length) { console.error('usage: publish.mjs [--branch b] [--org o] [--report-url u] [--dry] BOOK [BOOK...]'); process.exit(2); }

const { token } = getConfig();
if (!token && !DRY) { console.error('publish: no Door43 token (DOOR43_TOKEN); use --dry to preview'); process.exit(2); }
if (/^AI-/.test(BRANCH)) { console.error('publish: AI-* branches are the bot\'s auto-merge lane; pick another name'); process.exit(2); }

const repoDir = path.join(lib.WORK_DIR, 'en_tn-publish');
await syncRepo(repoDir, 'en_tn', BRANCH, 'master', ORG);

const lines = [];
let snapshot = '';
let total = 0;
// Splice and prove every book before the first commit, so a book that fails
// its proof cannot leave earlier books pushed with no PR.
const plans = [];
for (const book of books) {
  const dir = path.join(lib.WORK_DIR, 'output/modernize', book);
  const results = fs.readFileSync(path.join(dir, 'results.jsonl'), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
  snapshot = results.find((r) => r.templates_snapshot)?.templates_snapshot || snapshot;
  const file = `tn_${book}.tsv`;
  const before = fs.readFileSync(path.join(repoDir, file), 'utf8');
  const { text, applied, stale, missing } = applyResults(before, results);
  const problems = diffOnlyNotes(before, text, applied, lib.parseTnTsv);
  if (problems.length) throw new Error(`${book}: refusing to publish, ${problems.slice(0, 5).join('; ')}`);
  plans.push({ book, file, text, applied, stale, missing, looked: results.length });
}
for (const { book, file, text, applied, stale, missing, looked } of plans) {
  const line = `- ${book}: ${applied.length} notes rewritten of ${looked} looked at` +
    (stale.length ? `; ${stale.length} left alone because the note changed on master since extract (${stale.join(', ')})` : '') +
    (missing.length ? `; ${missing.length} IDs no longer on master` : '');
  console.log(line.slice(2));
  lines.push(line);
  total += applied.length;
  fs.writeFileSync(path.join(repoDir, file), text);
  if (DRY || !applied.length) continue;
  // checkConflictingBranches looks in unfoldingWord only.
  const conflicts = ORG === 'unfoldingWord' ? await checkConflictingBranches('en_tn', file) : [];
  if (conflicts.length) lines.push(`  - open PRs that also touch ${file}: ${conflicts.map((c) => `#${c.pr}`).join(', ')}`);
  await commitAndPush(repoDir, BRANCH, file,
    `${book}: rewrite ${applied.length} pre-template notes into the current templates\n\nNote column only. Templates snapshot ${snapshot}. Generated by bp-assistant scripts/tn-modernize.`);
}

const body = [
  `Rewrites old-style translation notes into the current note templates (snapshot ${snapshot}). **Review before merging. Nothing here was merged automatically.**`,
  '',
  `Only the Note column changes. For every book, the script checked that no other cell and no other row changed, and that each rewritten row's note on master still matched the text it was rewritten from.`,
  `A note was rewritten only when the model's version kept every alternate translation word for word, bolded only ULT words, kept every name and scripture reference, followed its template, and passed a separate check that each piece of information in the old note is still there. Everything else is unchanged.`,
  '',
  ...lines,
  '',
  REPORT ? `Side-by-side review of every change, flagged rows first: ${REPORT}` : 'Review report: see the tn-modernize run.',
].join('\n');

if (DRY) {
  console.log(`\n--- DRY: ${total} notes spliced into ${repoDir} on local branch ${BRANCH}; nothing committed or pushed. PR body would be:\n\n${body}`);
  process.exit(0);
}
if (!total) { console.log('nothing to publish'); process.exit(0); }
const pr = await createPR(token, 'en_tn', BRANCH, `Modernize notes to current templates: ${books.join(', ')}`, 'master', ORG, { body });
console.log(pr.success ? `PR #${pr.prNumber} open (not merged): ${pr.url}` : `PR not opened: ${pr.details}`);
process.exit(pr.success ? 0 : 1);
